#!/usr/bin/env python3
"""Measure the benchmarks and write benchmarks/report.md.

Wall clock is the best of RUNS runs (process start included). Peak RSS is the
child's own high-water mark, read from the platform `time` tool, so one program
cannot hide inside another's number.

    RUNS=3 ./run.sh            # or: python3 benchmarks/run.py

Only tools that are installed are measured; a missing one is left out with a
note in the report.
"""

from __future__ import annotations

import os
import platform
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
KODE = ROOT / "target" / "debug" / "kode"
BUILD = HERE / "build"
RUNS = int(os.environ.get("RUNS", "3"))
PROGRAMS = ["fib", "loop_mod", "sieve", "mandel", "collatz"]
TIME = shutil.which("time") or "/usr/bin/time"


def best_ms(cmd: list[str], cwd: Path) -> float | None:
    best = None
    for _ in range(RUNS):
        start = time.perf_counter()
        try:
            r = subprocess.run(cmd, cwd=cwd, capture_output=True, timeout=180)
        except (subprocess.TimeoutExpired, OSError):
            return None
        if r.returncode != 0:
            return None
        ms = (time.perf_counter() - start) * 1000.0
        best = ms if best is None else min(best, ms)
    return best


def peak_rss_kb(cmd: list[str], cwd: Path) -> int | None:
    """Peak RSS of one run, in kilobytes."""
    if not Path(TIME).exists():
        return None
    flag = "-l" if platform.system() == "Darwin" else "-v"
    try:
        r = subprocess.run([TIME, flag, *cmd], cwd=cwd, capture_output=True, text=True, timeout=180)
    except (subprocess.TimeoutExpired, OSError):
        return None
    # macOS reports bytes, with the number before the label.
    m = re.search(r"(\d+)\s+maximum resident set size", r.stderr, re.IGNORECASE)
    if m:
        return int(m.group(1)) // 1024
    # Linux reports kilobytes, with the number after the label.
    m = re.search(r"Maximum resident set size \(kbytes\):\s*(\d+)", r.stderr, re.IGNORECASE)
    if m:
        return int(m.group(1))
    return None


def have(tool: str) -> bool:
    return shutil.which(tool) is not None


def build(program: str, sources: dict[str, Path]) -> dict[str, list[str]]:
    """Build every available variant; return name -> command line."""
    out = BUILD / program
    out.mkdir(parents=True, exist_ok=True)
    runs: dict[str, list[str]] = {}

    kode_src = sources["kode"]
    exe = out / "program"
    r = subprocess.run(
        [str(KODE), "build", str(kode_src), "-o", str(exe), "--release"],
        capture_output=True, text=True,
    )
    if r.returncode == 0:
        runs["Kode"] = [str(exe)]

    if have("cc"):
        exe_c = out / "c"
        if subprocess.run(["cc", "-O2", "-o", str(exe_c), str(sources["c"])], capture_output=True).returncode == 0:
            runs["C"] = [str(exe_c)]
    if have("go"):
        exe_go = out / "go"
        if subprocess.run(["go", "build", "-o", str(exe_go), str(sources["go"])], capture_output=True).returncode == 0:
            runs["Go"] = [str(exe_go)]
    if have("node"):
        runs["Node"] = ["node", str(sources["js"])]
    if have("python3"):
        runs["Python"] = ["python3", str(sources["py"])]
    return runs


def main() -> int:
    if not KODE.exists():
        print(f"build the compiler first: cargo build --workspace ({KODE} is missing)", file=sys.stderr)
        return 1
    BUILD.mkdir(exist_ok=True)

    rows = []
    sizes = {}
    for program in PROGRAMS:
        d = HERE / program
        if not (d / "main.kode").exists():
            continue
        sources = {
            "kode": d / "main.kode",
            "c": d / "main.c",
            "go": d / "main.go",
            "js": d / "main.js",
            "py": d / "main.py",
        }
        runs = build(program, sources)
        row: dict[str, object] = {"program": program}
        for name, cmd in runs.items():
            row[f"{name} ms"] = best_ms(cmd, d)
            if row.get("rss") is None:
                row["rss"] = peak_rss_kb(cmd, d)
        if "Kode" in runs:
            exe = Path(runs["Kode"][0])
            if exe.exists():
                sizes[program] = exe.stat().st_size
        if row.get("Kode ms") and row.get("C ms"):
            row["Kode/C"] = row["Kode ms"] / row["C ms"]
        rows.append(row)
        print(f"measured {program}", file=sys.stderr)

    cols = ["program", "Kode ms", "C ms", "Go ms", "Node ms", "Python ms", "rss", "Kode/C"]
    lines = [
        "# Benchmark report",
        "",
        "Generated by `benchmarks/run.sh` (wall clock: best of "
        f"{RUNS}, RSS: peak of one run).",
        "",
        f"- machine: {platform.system()} {platform.release()} / {platform.machine()}",
        f"- compiler: {KODE}",
        f"- python: {platform.python_version()}",
        "",
        "| " + " | ".join(c.replace(" ms", " (ms)") for c in cols) + " |",
        "|" + "---|" * len(cols),
    ]
    for row in rows:
        cells = []
        for c in cols:
            v = row.get(c)
            if v is None:
                cells.append("—")
            elif c == "rss":
                cells.append(f"{v} KB")
            elif c == "Kode/C":
                cells.append(f"{v:.2f}×")
            elif c.endswith(" ms"):
                cells.append(f"{v:.0f}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")

    if sizes:
        lines += ["", "## Binary size (`--release`, stripped)", ""]
        for program, size in sizes.items():
            lines.append(f"- `{program}`: {size / 1024:.0f} KB")

    lines += [
        "",
        "Ratios are against C `-O2` where both ran; a dash means the tool is not",
        "installed on this machine.",
        "",
    ]
    report = HERE / "report.md"
    report.write_text("\n".join(lines))
    print(f"wrote {report}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
