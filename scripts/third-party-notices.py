#!/usr/bin/env python3
"""Write the third-party notices that ship with a Kode release.

The compiler links 37 crates from crates.io, and `kode-rt` is linked into every
program Kode compiles. A release tarball, and any binary built with `kode build`,
therefore contains their object code, and Apache-2.0, MIT, ISC, BSD-3-Clause and
CDLA-Permissive-2.0 all require their notices to travel with it.

    python3 scripts/third-party-notices.py           # rewrite the file
    python3 scripts/third-party-notices.py --check   # exit 1 if it is stale

Crate names, versions and license ids come from `cargo metadata --locked`; the
license texts are the copies inside the crate packages Cargo already downloaded.
Nothing else is read, and nothing is fetched over the network.
"""

import argparse
import glob
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.md")
LICENSE_GLOBS = ("LICEN[CS]E*", "COPYING*", "NOTICE*")


def cargo_metadata():
    command = ["cargo", "metadata", "--format-version", "1", "--locked"]
    try:
        raw = subprocess.check_output(command, cwd=ROOT, stderr=subprocess.PIPE)
    except FileNotFoundError:
        sys.exit("third-party-notices: cargo is not on PATH")
    except subprocess.CalledProcessError as error:
        detail = error.stderr.decode("utf-8", "replace").strip()
        sys.exit("third-party-notices: cargo metadata failed:\n" + detail)
    return json.loads(raw)


def license_files(directory):
    paths = []
    for pattern in LICENSE_GLOBS:
        paths.extend(glob.glob(os.path.join(directory, pattern)))
    return sorted(path for path in paths if os.path.isfile(path))


def read_text(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read().replace("\r\n", "\n").replace("\r", "\n").strip()


def short_source(package):
    url = package.get("repository") or package.get("homepage") or ""
    for prefix in ("https://", "http://"):
        if url.startswith(prefix):
            url = url[len(prefix):]
    return url.rstrip("/")


def render(metadata):
    members = set(metadata["workspace_members"])
    crates = sorted(
        (package for package in metadata["packages"] if package["id"] not in members),
        key=lambda package: (package["name"], package["version"]),
    )

    texts = {}
    without_text = []
    for package in crates:
        files = license_files(os.path.dirname(package["manifest_path"]))
        if not files:
            without_text.append(package)
            continue
        label = "{} {}".format(package["name"], package["version"])
        for path in files:
            body = read_text(path)
            if not body:
                continue
            digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
            entry = texts.setdefault(
                digest, {"name": os.path.basename(path), "body": body, "crates": []}
            )
            entry["crates"].append(label)

    lines = []
    add = lines.append
    add("# Third-party notices")
    add("")
    add("Kode itself is licensed under the Apache License 2.0 ([LICENSE](LICENSE));")
    add("this file covers the code it links, not Kode's own source.")
    add("")
    add(
        "A release archive contains `kode`, and every program built with `kode build`"
    )
    add(
        "embeds the Kode runtime. Both therefore distribute object code from the"
    )
    add(
        "{} crates below, and their licenses require their notices to travel with it.".format(
            len(crates)
        )
    )
    add(
        "Ship this file together with `LICENSE` when you redistribute a Kode binary."
    )
    add("")
    add(
        "Where a crate declares a choice (`A OR B`), Kode uses it under a license that"
    )
    add("is compatible with Apache-2.0; the declaration is reproduced as published.")
    add("")
    add(
        "Generated by `scripts/third-party-notices.py` from `Cargo.lock`. Do not edit:"
    )
    add("run the script after changing a dependency, and")
    add("`python3 scripts/third-party-notices.py --check` (which CI runs) verifies it.")
    add("")
    add("## Crates")
    add("")
    add("| crate | version | license | source |")
    add("|---|---|---|---|")
    for package in crates:
        add(
            "| {} | {} | {} | {} |".format(
                package["name"],
                package["version"],
                package.get("license") or "see repository",
                short_source(package) or "-",
            )
        )

    add("")
    add("## License texts")
    add("")
    add("{} distinct texts, deduplicated by content.".format(len(texts)))
    for digest in sorted(texts, key=lambda key: (texts[key]["name"], key)):
        entry = texts[digest]
        used_by = sorted(set(entry["crates"]))
        add("")
        add("### {} ({})".format(entry["name"], used_by[0]))
        add("")
        add("Used by: " + ", ".join(used_by) + ".")
        add("")
        add("~~~~text")
        add(entry["body"])
        add("~~~~")

    if without_text:
        add("")
        add("## Crates whose package does not include its license text")
        add("")
        add(
            "These crates declare the license below but ship no license file in the"
        )
        add(
            "published package, so no text can be copied here. They are Windows-host"
        )
        add(
            "dependencies in this graph; the text is in each crate's repository."
        )
        add("")
        add("| crate | version | license | source |")
        add("|---|---|---|---|")
        for package in without_text:
            add(
                "| {} | {} | {} | {} |".format(
                    package["name"],
                    package["version"],
                    package.get("license") or "see repository",
                    short_source(package) or "-",
                )
            )

    add("")
    return "\n".join(lines)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed file does not match the dependency graph",
    )
    args = parser.parse_args(argv)

    rendered = render(cargo_metadata())

    if args.check:
        try:
            with open(OUTPUT, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            sys.exit(
                "third-party-notices: THIRD-PARTY-NOTICES.md is missing; "
                "run python3 scripts/third-party-notices.py"
            )
        if current != rendered:
            sys.exit(
                "third-party-notices: THIRD-PARTY-NOTICES.md is stale; "
                "run python3 scripts/third-party-notices.py and commit the result"
            )
        print("third-party-notices: up to date")
        return 0

    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print("third-party-notices: wrote {} ({} bytes)".format(OUTPUT, len(rendered)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
