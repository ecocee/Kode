//! `kode doc <folder> [-o dir]`: a small HTML reference for `pub` items.
//!
//! Signatures are read from the source text, not from the checked program, so
//! a folder documents what it declares even while it is being edited. Only the
//! declaration line and the `///` lines directly above it are used; bodies are
//! never copied.

use std::path::PathBuf;

use crate::args::Options;

struct Entry {
    doc: Vec<String>,
    sig: String,
}

pub fn run(opts: &Options) -> Result<u8, String> {
    let roots: Vec<String> = if opts.files.is_empty() {
        vec![".".into()]
    } else {
        opts.files.clone()
    };
    let files = crate::collect_kode_files(&roots)?;
    let out = PathBuf::from(opts.output.clone().unwrap_or_else(|| "docs/api".into()));

    let mut pages: Vec<(String, Vec<Entry>)> = Vec::new();
    for file in &files {
        let text =
            std::fs::read_to_string(file).map_err(|e| format!("cannot read {}: {e}", file.display()))?;
        let items = entries(&text);
        if !items.is_empty() {
            pages.push((file.display().to_string(), items));
        }
    }
    if pages.is_empty() {
        return Err("no `pub` items to document".into());
    }

    std::fs::create_dir_all(&out).map_err(|e| format!("cannot create {}: {e}", out.display()))?;
    let index = out.join("index.html");
    std::fs::write(&index, html(&pages))
        .map_err(|e| format!("cannot write {}: {e}", index.display()))?;
    let total: usize = pages.iter().map(|(_, items)| items.len()).sum();
    println!(
        "wrote {} ({} items from {} files)",
        index.display(),
        total,
        pages.len()
    );
    Ok(0)
}

/// `pub` declarations with their doc comment and their signature line.
fn entries(text: &str) -> Vec<Entry> {
    let mut out = Vec::new();
    let mut doc: Vec<String> = Vec::new();
    let lines: Vec<&str> = text.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let trimmed = lines[i].trim_start();
        if let Some(rest) = trimmed.strip_prefix("///") {
            doc.push(rest.trim_start().to_string());
            i += 1;
            continue;
        }
        if !trimmed.starts_with("pub ") {
            if !trimmed.is_empty() {
                doc.clear();
            }
            i += 1;
            continue;
        }
        let mut sig = trimmed.to_string();
        // A declaration can wrap; keep going until the body opens.
        while !sig.ends_with('{')
            && !sig.ends_with('}')
            && !sig.ends_with(';')
            && i + 1 < lines.len()
        {
            let next = lines[i + 1].trim();
            if next.is_empty() || next.starts_with("///") || next.starts_with('#') {
                break;
            }
            i += 1;
            sig.push(' ');
            sig.push_str(next);
        }
        let sig = sig.trim_end_matches('{').trim_end().to_string();
        out.push(Entry {
            doc: std::mem::take(&mut doc),
            sig,
        });
        i += 1;
    }
    out
}

fn html(pages: &[(String, Vec<Entry>)]) -> String {
    let mut s = String::from(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\
         <title>Kode API</title><style>\
         body{font:16px/1.55 system-ui,sans-serif;max-width:52rem;margin:3rem auto;padding:0 1rem;background:#fbfaf7;color:#232323}\
         h1{font-size:1.7rem;margin-bottom:.3rem}h2{font-size:1rem;letter-spacing:.04em;text-transform:uppercase;color:#6b6b6b;border-bottom:1px solid #e2ddd2;padding-bottom:.35rem;margin-top:2.4rem}\
         pre{white-space:pre-wrap;margin:.25rem 0}\
         .doc{color:#44603f;font-size:.88rem}\
         .sig{background:#fff;border:1px solid #e6e2da;border-left:3px solid #7a9e6f;padding:.55rem .8rem;border-radius:4px;overflow:auto}\
         footer{margin-top:3rem;color:#8a8a8a;font-size:.85rem}\
         </style></head><body>\n<h1>Kode API</h1>\n",
    );
    for (file, items) in pages {
        s.push_str(&format!("<section><h2>{}</h2>\n", esc(file)));
        for e in items {
            if !e.doc.is_empty() {
                s.push_str(&format!(
                    "<pre class=\"doc\">{}</pre>\n",
                    esc(&e.doc.join("\n"))
                ));
            }
            s.push_str(&format!("<pre class=\"sig\">{}</pre>\n", esc(&e.sig)));
        }
        s.push_str("</section>\n");
    }
    s.push_str("<footer>Generated by <code>kode doc</code>.</footer>\n</body></html>\n");
    s
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
