//! Dependency resolution. Dependencies are path packages, resolved
//! transitively into one flat namespace: every package name is unique.
//!
//! There is no registry, so a `version` in `[dependencies]` is a compatibility
//! check against the version in that package's own `kode.toml`.

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

use kode_diagnostics::Diagnostic;

use crate::manifest::{self, Manifest};

#[derive(Clone, Debug)]
pub struct Resolved {
    pub name: String,
    pub version: String,
    /// Source root of the dependency (where its bare imports resolve).
    pub root: PathBuf,
    /// The folder that holds its `kode.toml`.
    pub dir: PathBuf,
}

/// Resolve every direct and indirect dependency of `top`.
pub fn dependencies(top: &Manifest) -> Result<Vec<Resolved>, Diagnostic> {
    let mut found: HashMap<String, Resolved> = HashMap::new();
    let mut seen_dirs: HashSet<PathBuf> = HashSet::new();
    let mut queue: Vec<Manifest> = vec![top.clone()];
    seen_dirs.insert(canon(&top.dir));

    while let Some(manifest) = queue.pop() {
        for dep in &manifest.deps {
            if dep.name == top.name {
                return Err(code(
                    "E0414",
                    format!("`{}` depends on itself through `{}`", top.name, dep.name),
                ));
            }
            let file = dep.path.join("kode.toml");
            if !file.is_file() {
                return Err(code(
                    "E0412",
                    format!(
                        "dependency `{}` is not a package: {} has no kode.toml",
                        dep.name,
                        dep.path.display()
                    ),
                )
                .with_help(format!(
                    "check the `path` for `{}` in {}",
                    dep.name,
                    manifest.dir.join("kode.toml").display()
                )));
            }
            let dep_manifest = manifest::read(&file)?;
            // The name in `[dependencies]` is what imports use, so it has to be
            // the package's own name. Renaming would make imports lie.
            if dep_manifest.name != dep.name {
                return Err(code(
                    "E0414",
                    format!(
                        "`{}` calls a package `{}`, but {} is named `{}`",
                        manifest.name,
                        dep.name,
                        dep.path.display(),
                        dep_manifest.name
                    ),
                )
                .with_help(format!(
                    "rename the dependency to `{}`, or rename the package",
                    dep_manifest.name
                )));
            }
            if let Some(want) = &dep.version {
                if want != &dep_manifest.version {
                    return Err(code(
                        "E0413",
                        format!(
                            "`{}` needs `{}` version {want}, but {} is {}",
                            manifest.name,
                            dep.name,
                            dep.path.display(),
                            dep_manifest.version
                        ),
                    )
                    .with_help("change the version in `kode.toml`, or update the dependency"));
                }
            }
            if let Some(existing) = found.get(&dep.name) {
                if canon(&existing.dir) != canon(&dep.path) {
                    return Err(code(
                        "E0414",
                        format!(
                            "two packages are both called `{}`: {} and {}",
                            dep.name,
                            existing.dir.display(),
                            dep.path.display()
                        ),
                    )
                    .with_help("rename one of them; dependency names share one namespace"));
                }
                continue;
            }
            found.insert(
                dep.name.clone(),
                Resolved {
                    name: dep.name.clone(),
                    version: dep_manifest.version.clone(),
                    root: dep_manifest.root.clone(),
                    dir: dep_manifest.dir.clone(),
                },
            );
            if seen_dirs.insert(canon(&dep.path)) {
                queue.push(dep_manifest);
            }
        }
    }

    let mut list: Vec<Resolved> = found.into_values().collect();
    list.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(list)
}

/// The lockfile text for these dependencies. Deterministic: same input, same bytes.
pub fn lock_text(top: &Manifest, deps: &[Resolved]) -> String {
    let mut out = String::from("# generated by `kode install`; commit this file\nversion = 1\n");
    for dep in deps {
        out.push_str("\n[[package]]\n");
        out.push_str(&format!("name = \"{}\"\n", dep.name));
        out.push_str(&format!("version = \"{}\"\n", dep.version));
        out.push_str(&format!(
            "path = \"{}\"\n",
            relative_path(&top.dir, &dep.dir)
        ));
    }
    out
}

/// A path from `from` to `to`, using `..` where needed.
fn relative_path(from: &Path, to: &Path) -> String {
    let from = canon(from);
    let to = canon(to);
    let fc: Vec<_> = from.components().collect();
    let tc: Vec<_> = to.components().collect();
    let common = fc.iter().zip(&tc).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".to_string(); fc.len() - common];
    parts.extend(
        tc[common..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().to_string()),
    );
    if parts.is_empty() {
        ".".to_string()
    } else {
        parts.join("/")
    }
}

fn canon(path: &Path) -> PathBuf {
    path.canonicalize().unwrap_or_else(|_| path.to_path_buf())
}

fn code(code: &'static str, message: String) -> Diagnostic {
    Diagnostic::error(code, message, Default::default())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn package(dir: &Path, name: &str, deps: &str) {
        std::fs::create_dir_all(dir.join("src")).unwrap();
        std::fs::write(
            dir.join("kode.toml"),
            format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nroot = \"src\"\n{deps}"),
        )
        .unwrap();
        std::fs::write(dir.join("src/lib.kode"), "pub fn value() -> int => 1\n").unwrap();
    }

    fn workspace(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("kode-resolve-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn resolves_direct_and_indirect_dependencies() {
        let dir = workspace("chain");
        package(&dir.join("c"), "c", "");
        package(
            &dir.join("b"),
            "b",
            "\n[dependencies]\nc = { path = \"../c\" }\n",
        );
        package(
            &dir.join("a"),
            "a",
            "\n[dependencies]\nb = { path = \"../b\" }\n",
        );
        let top = manifest::read(&dir.join("a/kode.toml")).unwrap();
        let deps = dependencies(&top).unwrap();
        let names: Vec<&str> = deps.iter().map(|d| d.name.as_str()).collect();
        assert_eq!(names, vec!["b", "c"]);
        assert!(lock_text(&top, &deps).contains("name = \"c\""));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn reports_a_missing_package() {
        let dir = workspace("missing");
        package(
            &dir.join("a"),
            "a",
            "\n[dependencies]\nghost = { path = \"../ghost\" }\n",
        );
        let top = manifest::read(&dir.join("a/kode.toml")).unwrap();
        let err = dependencies(&top).unwrap_err();
        assert_eq!(err.code, "E0412");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn reports_a_version_mismatch() {
        let dir = workspace("version");
        package(&dir.join("u"), "u", "");
        package(
            &dir.join("a"),
            "a",
            "\n[dependencies]\nu = { path = \"../u\", version = \"9.9\" }\n",
        );
        let top = manifest::read(&dir.join("a/kode.toml")).unwrap();
        let err = dependencies(&top).unwrap_err();
        assert_eq!(err.code, "E0413");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn reports_a_dependency_renamed_by_its_importer() {
        let dir = workspace("clash");
        package(&dir.join("two/u"), "u", "");
        package(
            &dir.join("a"),
            "a",
            "\n[dependencies]\nother = { path = \"../two/u\" }\n",
        );
        let top = manifest::read(&dir.join("a/kode.toml")).unwrap();
        let err = dependencies(&top).unwrap_err();
        assert_eq!(err.code, "E0414");
        assert!(err.message.contains("other"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn reports_a_dependency_cycle() {
        let dir = workspace("cycle");
        package(
            &dir.join("b"),
            "b",
            "\n[dependencies]\na = { path = \"../a\" }\n",
        );
        package(
            &dir.join("a"),
            "a",
            "\n[dependencies]\nb = { path = \"../b\" }\n",
        );
        let top = manifest::read(&dir.join("a/kode.toml")).unwrap();
        assert_eq!(dependencies(&top).unwrap_err().code, "E0414");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn lock_paths_are_relative_to_the_package() {
        let dir = workspace("lock");
        package(&dir.join("libs/utils"), "utils", "");
        package(
            &dir.join("app"),
            "app",
            "\n[dependencies]\nutils = { path = \"../libs/utils\" }\n",
        );
        let top = manifest::read(&dir.join("app/kode.toml")).unwrap();
        let deps = dependencies(&top).unwrap();
        assert!(lock_text(&top, &deps).contains("path = \"../libs/utils\""));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
