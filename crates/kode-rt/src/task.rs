//! `spawn` / `await`: tasks run on their own threads and share nothing.
//! A task gets plain values (ints, floats, bools, strings) and returns one result.

use std::sync::atomic::Ordering;
use std::thread::{Builder, JoinHandle};

use crate::error::{fatal, kode_err_throw, take_err};
use crate::object::{alloc_object, free_object, kode_release, Header, TASK, THREADED};

struct TaskInner {
    handle: Option<JoinHandle<(u64, usize)>>,
    result_is_ref: bool,
}

type Thunk = extern "C" fn(*mut Header) -> i64;

/// Start a task. `thunk(block)` runs on the new thread; the task owns `block`.
///
/// # Safety
/// `thunk` must be a function generated by the compiler and `block` its argument block.
#[no_mangle]
pub unsafe extern "C" fn kode_task_spawn(thunk: Thunk, block: *mut Header, result_is_ref: i64) -> *mut Header {
    THREADED.store(true, Ordering::SeqCst);
    let (f, b) = (thunk as usize, block as usize);
    let handle = Builder::new()
        .stack_size(64 << 20)
        .spawn(move || {
            let thunk: Thunk = std::mem::transmute(f);
            let raw = thunk(b as *mut Header) as u64;
            kode_release(b as *mut Header);
            (raw, take_err() as usize)
        })
        .unwrap_or_else(|e| fatal(&format!("cannot start a task: {e}")));
    let p = alloc_object(24, TASK);
    let inner = Box::new(TaskInner {
        handle: Some(handle),
        result_is_ref: result_is_ref != 0,
    });
    *((p as *mut *mut TaskInner).add(2)) = Box::into_raw(inner);
    p
}

/// Wait for a task and take its result (the caller owns it). If the task failed,
/// the error is raised here.
///
/// # Safety
/// `t` must be a task.
#[no_mangle]
pub unsafe extern "C" fn kode_task_await(t: *mut Header) -> i64 {
    let inner = &mut **((t as *mut *mut TaskInner).add(2));
    let Some(h) = inner.handle.take() else {
        fatal("this task was already awaited");
    };
    let (raw, err) = h.join().unwrap_or_else(|_| fatal("a task crashed"));
    if err != 0 {
        kode_err_throw(err as *mut Header);
        return 0;
    }
    raw as i64
}

/// A task that was never awaited: wait for it and free what it produced.
pub unsafe fn drop_task(p: *mut Header) {
    let inner = Box::from_raw(*((p as *mut *mut TaskInner).add(2)));
    if let Some(h) = inner.handle {
        if let Ok((raw, err)) = h.join() {
            if inner.result_is_ref {
                kode_release(raw as *mut Header);
            }
            kode_release(err as *mut Header);
        }
    }
    free_object(p, 24);
}